#!/usr/bin/env python3
"""
Regenerate the parameter table in docs/GAUGE_AUTHORING.md section 6 from
src/managers/parametercatalog.cpp, so the doc lists every id the catalog has.

The table sits between the BEGIN/END markers in the doc; everything else in
the doc is hand-written. tst_parametercatalog fails when an id is missing
from the doc, which is the cue to run this.

Usage:
    python scripts/gen_gauge_param_docs.py
"""

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CATALOG = ROOT / "src/managers/parametercatalog.cpp"
PROTOCOL = ROOT / "src/managers/elm327protocol.cpp"
MODEL = ROOT / "frontend/OBDParameterModel.qml"
DOC = ROOT / "docs/GAUGE_AUTHORING.md"
BEGIN = "<!-- BEGIN generated by scripts/gen_gauge_param_docs.py -->"
END = "<!-- END generated -->"

ROW = re.compile(
    r'\{"(\w+)", "([^"]*)", "([^"]*)", "([^"]*)", ([-\d.]+), ([-\d.]+), "(\w+)", (\d), '
    r'Source::(\w+), "(\w*)"\}'
)


def num(text):
    value = float(text)
    return str(int(value)) if value.is_integer() else str(value)


def main():
    rows = ROW.findall(CATALOG.read_text(encoding="utf-8"))
    if not rows:
        sys.exit("no catalog rows found in " + str(CATALOG))
    multi = set(re.findall(r'sig\("(\w+)"', PROTOCOL.read_text(encoding="utf-8")))
    model = MODEL.read_text(encoding="utf-8")
    core = re.findall(r'"(\w+)"', model[model.index("originalParameters"):model.index("]", model.index("originalParameters"))])

    groups = [
        ("Core (default-enabled)", lambda r: r[0] in core),
        ("More single-value OBD PIDs", lambda r: r[8] == "Obd" and r[0] not in core and r[0] not in multi),
        ("Multi-value OBD PIDs (0x61 and up, via obdParameterChanged)", lambda r: r[0] in multi),
        ("Sensor parameters (BerryIMU, not OBD)", lambda r: r[8] == "Imu"),
    ]
    out = [BEGIN, ""]
    listed = 0
    for title, keep in groups:
        chosen = [r for r in rows if keep(r)]
        listed += len(chosen)
        out.append(f"### {title} ({len(chosen)})")
        out.append("")
        out.append("| `paramId` | Title | Short | Unit | Min | Max | Kind | Decimals |")
        out.append("| --- | --- | --- | --- | ---: | ---: | --- | ---: |")
        for (pid, name, short, unit, lo, hi, kind, dec, _src, alias) in chosen:
            label = name + (f" (alias of `{alias}`)" if alias else "")
            out.append(f"| `{pid}` | {label} | {short} | {unit} | {num(lo)} | {num(hi)} | {kind} | {dec} |")
        out.append("")
    if listed != len(rows):
        sys.exit(f"grouping lost ids: {listed} of {len(rows)}")
    out.append(END)

    doc = DOC.read_text(encoding="utf-8")
    start, stop = doc.index(BEGIN), doc.index(END) + len(END)
    DOC.write_text(doc[:start] + "\n".join(out) + doc[stop:], encoding="utf-8")
    print(f"{DOC.relative_to(ROOT)}: {len(rows)} parameters")


if __name__ == "__main__":
    main()
