def _placement(board):
    # to the micron: a saved board comes back rounded
    return sorted((fp.GetReference(), round(fp.GetPosition().x / 1000), round(fp.GetPosition().y / 1000),
                   round(fp.GetOrientationDegrees()) % 360, fp.IsFlipped()) for fp in board.GetFootprints())


def _freeze(board):
    """Save the routed copper: `route` replays it, so a rebuild gives the same board (Freerouting
    does not give the same answer twice)."""
    import pcbnew
    items = []
    for it in _snapshot(board):
        if it[0] == "via":
            items.append(["via", it[1].x, it[1].y, it[2], it[3], it[4]])
        else:
            items.append(["trk", it[1].x, it[1].y, it[2].x, it[2].y, it[3], pcbnew.LayerName(it[4]), it[5]])
    with open(FROZEN, "w") as f:
        json.dump({"placement": [list(p) for p in _placement(board)], "items": items}, f)
    print("routing frozen in gen/routing.json:", len(items), "tracks and vias")


def _replay(board):
    import pcbnew
    data = json.load(open(FROZEN))
    now = _placement(board)
    same = len(now) == len(data["placement"]) and all(
        a[0] == o[0] and abs(a[1] - o[1]) <= 2 and abs(a[2] - o[2]) <= 2 and a[3] == o[3] and a[4] == o[4]
        for a, o in zip(now, data["placement"]))
    if not same:
        sys.exit("parts have moved since the routing was frozen: KNOB_REROUTE=1 python3 build.py route")
    lay = {pcbnew.LayerName(i): i for i in (pcbnew.F_Cu, pcbnew.In1_Cu, pcbnew.In2_Cu, pcbnew.B_Cu)}
    V = pcbnew.VECTOR2I
    _restore(board, [("via", V(i[1], i[2]), i[3], i[4], i[5]) if i[0] == "via" else
                     ("trk", V(i[1], i[2]), V(i[3], i[4]), i[5], lay[i[6]], i[7]) for i in data["items"]])
    return len(data["items"])


def route():
    """Hand copper (prewire.py), ground fan-out, Freerouting for the rest, ground pours, DRC.
    Replays gen/routing.json when there is one; KNOB_REROUTE=1 routes afresh and freezes the result."""
    import math
    import pcbnew
    import layout
    import pcbgen
    import prewire
    work = os.path.join(PROJ, "route")
    os.makedirs(work, exist_ok=True)
    dsn, ses = os.path.join(work, NAME + ".dsn"), os.path.join(work, NAME + ".ses")
    board = pcbnew.LoadBoard(PCB)
    for t in list(board.GetTracks()):
        board.Remove(t)
    for z in list(board.Zones()):
        if not z.GetIsRuleArea() and z.GetLayer() != pcbnew.In1_Cu:
            board.Remove(z)
    cx, cy = layout.CX, layout.CY
    if os.path.exists(FROZEN) and not os.environ.get("KNOB_REROUTE"):
        print("routing: replayed", _replay(board), "frozen tracks and vias from gen/routing.json")
        for layer in (pcbnew.F_Cu, pcbnew.B_Cu, pcbnew.In2_Cu):
            pcbgen.circle_zone(board, board.FindNet("GND"), layer, cx, cy, layout.R_BOARD, solid=True)
        pcbnew.ZONE_FILLER(board).Fill(board.Zones())
        board.Save(PCB)
        drc()
        return
    prewire.wire(board)
    ax0, ay0, ax1, ay1 = layout.ANTENNA
    sw = board.FindFootprintByReference("SW1").GetPosition()

    def allow(x, y):
        """A fan-out via may go here: on the board, off the antenna, off the encoder's body and
        the screw heads."""
        x, y = x - cx, y - cy
        if math.hypot(x, y) > layout.R_BOARD - 0.8:
            return False
        if y <= layout.ANTENNA_Y + 0.5:
            return False
        if 2.85 <= abs(x) <= 6.8 and 2.45 <= abs(y) <= 5.3:   # where the encoder's metal frame sits on the board
            return False
        if math.hypot(x, y) < 1.9 or math.hypot(x, y - 4.5) < 1.9:    # its boss and locating pin
            return False
        if any(math.hypot(x - fx, y - fy) < 1.7 for fx, fy, _ in layout.FIDUCIALS):
            return False
        return all(math.hypot(x - hx, y - hy) > layout.HOLE_KEEP + 0.4 for hx, hy in layout.HOLES)

    # every ground pad gets its own via into the plane before the signals are routed (afterwards
    # there is not always room); the module's and the boost converter's are prewire.py's
    refs = {fp.GetReference() for fp in board.GetFootprints()} - {"U4", "U6"}
    bad = pcbgen.fanout(board, "GND", pcbnew.In1_Cu, via_d=0.5, drill=0.25, width=0.2, clearance=0.18,
                        refs=refs, allow=allow)
    print("GND fan-out before routing, pads without a via:", " ".join(bad) or "none")
    pre = _snapshot(board)
    for t in board.GetTracks():
        t.SetLocked(True)
    board.Save(PCB)

    def freeroute(log):
        pcbnew.ExportSpecctraDSN(board, dsn)
        with open(dsn) as f:
            text = _dsn_postprocess(f.read())
        with open(dsn, "w") as f:
            f.write(text)
        if os.environ.get("KNOB_KEEP_SES") and os.path.exists(ses):    # re-do only what follows the router
            pcbnew.ImportSpecctraSES(board, ses)
            return
        if os.path.exists(ses):
            os.remove(ses)
        subprocess.run(["timeout", "1500", "java", "-jar", FREEROUTING_JAR, "-de", dsn, "-do", ses,
                        "--gui.enabled=false", "--feature_flags.multi_threading=false", "-mp", "100",
                        "--router.automatic_neckdown=false", "--router.copper_to_edge_clearance_um=400",
                        "--usage_and_diagnostic_data.disable_analytics=true"],
                       stdout=open(os.path.join(work, log), "w"), stderr=subprocess.STDOUT)
        if not os.path.exists(ses):
            sys.exit(f"freerouting produced no session; see route/{log}")
        pcbnew.ImportSpecctraSES(board, ses)

    import maze
    wide = {n: w / 1000 for w, nets in WIDTHS.items() for n in nets}
    for i in range(3):
        freeroute(f"freerouting-{i + 1}.log")
        have = {_key(it) for it in _snapshot(board)}
        _restore(board, [it for it in pre if _key(it) not in have])
        # Freerouting can stall with a connection or two left: the grid router finishes them
        left = maze.finish(board, lambda n: wide.get(n.lstrip("/"), SIGNAL_WIDTH), lambda n: SIGNAL_CLEARANCE,
                           [], skip=("GND",))
        for narrow in (0.2, SIGNAL_WIDTH):   # a supply branch that cannot reach a fine pin at its own width
            if left:
                left = maze.finish(board, lambda n: min(narrow, wide.get(n.lstrip("/"), SIGNAL_WIDTH)),
                                   lambda n: SIGNAL_CLEARANCE, [], skip=("GND",), rip=True)
        print(f"pass {i + 1}: nets still in pieces after the finisher:", left or "none")
        if not left:
            break
    if bad:     # a second try for those, in the room the signals left, with a smaller via
        bad = pcbgen.fanout(board, "GND", pcbnew.In1_Cu, via_d=0.45, drill=0.2, width=0.15, clearance=0.135,
                            refs={s.split(".")[0] for s in bad}, allow=allow)
    print("GND pads without their own via (joined by the pours):", " ".join(bad) or "none")
    n = pcbgen.stitch(board, "GND", cx - layout.R_BOARD, cy - layout.R_BOARD, cx + layout.R_BOARD, cy + layout.R_BOARD, pitch=2.0, via_d=0.5, drill=0.25,
                      clearance=0.2, allow=allow, skip=("BT1",))
    print("GND stitching vias:", n)
    for t in board.GetTracks():   # Freerouting necks down at some pads despite the setting
        if t.Type() == pcbnew.PCB_TRACE_T and t.GetWidth() < pcbnew.FromMM(0.127):
            t.SetWidth(pcbnew.FromMM(0.127))
    print("vias the router left on one layer, removed:", _drop_dangling_vias(board, {_key(it) for it in pre}),
          "- stub tracks removed:", _drop_stubs(board))
    # pours join pads solidly (thermal spokes left pads cut off in the tight spots); the cell's hole,
    # soldered by hand, keeps its spokes (pcb())
    for layer in (pcbnew.F_Cu, pcbnew.B_Cu, pcbnew.In2_Cu):
        pcbgen.circle_zone(board, board.FindNet("GND"), layer, cx, cy, layout.R_BOARD, solid=True)
    for _ in range(3):
        pcbnew.ZONE_FILLER(board).Fill(board.Zones())
        left = _join_islands(board, allow)
        if not left:
            break
    pcbnew.ZONE_FILLER(board).Fill(board.Zones())
    print("ground pour pieces with no way into the plane:", left)
    board.Save(PCB)
    drc()
    if left or any(line.startswith("[") and not line.startswith(("[npth_inside", "[lib_footprint", "[silk"))
                   for line in open(os.path.join(PROJ, "drc.rpt"))):
        print("NOT frozen: the rule check has findings beyond the known ones (see drc.rpt). Route again")
    else:
        _freeze(board)


def drc():
    rpt = os.path.join(PROJ, "drc.rpt")
    run(["kicad-cli", "pcb", "drc", "--schematic-parity", "--severity-all", PCB, "-o", rpt],
        capture_output=True)
    for line in open(rpt):
        if line.startswith("** Found"):
            print(line.strip())


def _natural(ref):
    head = ref.rstrip("0123456789")
    return head, int(ref[len(head):] or 0)


def fab():
    """Gerbers + drill (zipped), JLCPCB BOM and CPL, the list of parts to fit by hand, renders."""
    import csv
    import shutil
    import knob
    from jlc_corr import cpl
    out = os.path.join(PROJ, "fab")
    gdir = os.path.join(out, "gerbers")
    shutil.rmtree(out, ignore_errors=True)
    os.makedirs(gdir)
    layers = "F.Cu,In1.Cu,In2.Cu,B.Cu,F.Paste,B.Paste,F.Silkscreen,B.Silkscreen,F.Mask,B.Mask,Edge.Cuts"
    run(["kicad-cli", "pcb", "export", "gerbers", "--layers", layers, "--subtract-soldermask",
         "-o", gdir + "/", PCB], capture_output=True)
    run(["kicad-cli", "pcb", "export", "drill", "--format", "excellon", "--excellon-separate-th",
         "-o", gdir + "/", PCB], capture_output=True)   # no drill map: it invites a CAM query
    shutil.make_archive(os.path.join(out, f"{NAME}-rev{REV}-gerbers"), "zip", gdir)
    groups, hand = {}, []
    for p in knob.d.parts:
        if p.dnp:
            continue
        if not p.lcsc:
            if not p.lib_id.startswith("Connector:TestPoint"):
                hand.append(p)
            continue
        groups.setdefault((p.value, p.footprint.split(":")[1], p.lcsc), []).append(p.ref)
    with open(os.path.join(out, f"{NAME}-rev{REV}-bom-jlcpcb.csv"), "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["Comment", "Designator", "Footprint", "LCSC"])
        for (val, fp, lcsc), refs in sorted(groups.items(), key=lambda kv: _natural(kv[1][0])):
            w.writerow([val, ",".join(sorted(refs, key=_natural)), fp, lcsc])
    with open(os.path.join(out, f"{NAME}-rev{REV}-hand-fit.txt"), "w") as f:
        f.write("Not assembled by JLCPCB (no LCSC number): fit by hand.\n\n")
        for p in hand:
            f.write(f"{p.ref:6} {p.value:22} {p.footprint}  {p.note}\n")
    pos = os.path.join(out, "pos.csv")
    run(["kicad-cli", "pcb", "export", "pos", "--format", "csv", "--units", "mm", "--side", "both",
         "--exclude-dnp", "-o", pos, PCB], capture_output=True)
    assembled = {r for refs in groups.values() for r in refs}
    lcsc_of = {p.ref: p.lcsc for p in knob.d.parts}
    with open(pos) as fin, open(os.path.join(out, f"{NAME}-rev{REV}-cpl-jlcpcb.csv"), "w", newline="") as fout:
        w = csv.writer(fout)
        w.writerow(["Designator", "Mid X", "Mid Y", "Layer", "Rotation"])
        for row in csv.DictReader(fin):
            if row["Ref"] not in assembled:
                continue
            # jlc_corr.cpl: JLCPCB's own footprint frames, and its rule for the bottom side
            x, y, rot = cpl(float(row["PosX"]), float(row["PosY"]), float(row["Rot"]), row["Side"],
                            lcsc_of[row["Ref"]])
            w.writerow([row["Ref"], f"{x:.4f}mm", f"{y:.4f}mm",
                        "Top" if row["Side"] == "top" else "Bottom", f"{rot:g}"])
    os.remove(pos)
    render()
    print("fab outputs in", out, ":", sorted(os.listdir(out)))
    print(len(assembled), "parts assembled,", len(groups), "BOM lines,", len(hand), "hand-fit")


def render():
    """Pictures of the board in renders/ (kicad-cli's raytracer; the cell, module and encoder are
    the plain shapes from mk3d.py)."""
    out = os.path.join(PROJ, "renders")
    os.makedirs(out, exist_ok=True)
    views = {"top": ["--side", "top"], "bottom": ["--side", "bottom"],
             "top-3d": ["--side", "top", "--perspective", "--rotate", "-50,0,25", "--zoom", "0.85"],
             "bottom-3d": ["--side", "bottom", "--perspective", "--rotate", "50,0,-25", "--zoom", "0.85"]}
    for name, args in views.items():
        run(["kicad-cli", "pcb", "render", *args, "--quality", "high", "--width", "1600", "--height", "1200",
             "-o", os.path.join(out, name + ".png"), PCB], capture_output=True)


