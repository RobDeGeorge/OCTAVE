def _snapshot(board):
    import pcbnew
    out = []
    for t in board.GetTracks():
        if t.Type() == pcbnew.PCB_VIA_T:
            out.append(("via", t.GetPosition(), t.GetWidth(pcbnew.F_Cu), t.GetDrillValue(), t.GetNetname()))
        else:
            out.append(("trk", t.GetStart(), t.GetEnd(), t.GetWidth(), t.GetLayer(), t.GetNetname()))
    return out


def _key(it):
    return ("via", it[1].x, it[1].y) if it[0] == "via" else ("trk", it[1].x, it[1].y, it[2].x, it[2].y, it[4])


def _restore(board, items):
    import pcbnew
    for it in items:
        if it[0] == "via":
            _, pos, w, drill, net = it
            v = pcbnew.PCB_VIA(board)
            v.SetPosition(pos)
            v.SetWidth(w)
            v.SetDrill(drill)
            v.SetNet(board.FindNet(net))
            board.Add(v)
        else:
            _, a, b, w, layer, net = it
            t = pcbnew.PCB_TRACK(board)
            t.SetStart(a)
            t.SetEnd(b)
            t.SetWidth(w)
            t.SetLayer(layer)
            t.SetNet(board.FindNet(net))
            board.Add(t)


def _dsn_postprocess(text):
    """In1.Cu becomes the GND plane; the default rule and the supply nets' widths are set here
    (LoadBoard does not read the net classes from the .kicad_pro)."""
    import re
    text = text.replace("(layer In1.Cu\n      (type signal)", "(layer In1.Cu\n      (type power)")
    text = re.sub(r"\(rule\s+\(width [\d.]+\)\s+\(clearance [\d.]+\)",
                  f"(rule\n      (width {SIGNAL_WIDTH * 1000:.0f})\n      (clearance {SIGNAL_CLEARANCE * 1000:.0f})",
                  text, count=1)
    # ground is the In1 plane plus the pours: give Freerouting one GND pin only, so it neither routes
    # ground as tracks nor finds the signals' escapes blocked by ground vias (those come afterwards)
    if os.environ.get("KNOB_GND") != "router":
        text = re.sub(r"\(net GND\s+\(pins (\S+)[^)]*\)", r"(net GND\n      (pins \1)", text)
    m = re.search(r"\(class kicad_default (.*?)\(circuit\s+\(use_via ([^)]+)\)", text, re.S)
    names, via = m.group(1).split(), m.group(2)
    special = {n for nets in WIDTHS.values() for n in nets}
    bare = lambda n: n.strip('"').lstrip("/")    # noqa: E731
    keep = [n for n in names if bare(n) not in special]
    classes = ""
    for w, nets in WIDTHS.items():
        have = [n for n in names if bare(n) in nets]
        classes += (f"(class w{w} {' '.join(have)}\n      (circuit\n        (use_via {via})\n      )\n"
                    f"      (rule\n        (width {w})\n        (clearance {SIGNAL_CLEARANCE * 1000:.0f})\n      )\n    )\n    ")
    return text[:m.start()] + classes + "(class kicad_default " + " ".join(keep) + "\n      (circuit\n        (use_via " + via + ")" + text[m.end():]


def _drop_dangling_vias(board, keep=()):
    """Signal vias with tracks on fewer than two layers (and no pad under them). `keep`: the keys
    of the hand-laid vias, which a track may pass through without ending on."""
    import pcbnew
    ends = {}
    for t in board.GetTracks():
        if t.Type() == pcbnew.PCB_TRACE_T:
            for p in (t.GetStart(), t.GetEnd()):
                ends.setdefault((t.GetNetCode(), p.x, p.y), set()).add(t.GetLayer())
    pads = {(p.GetNetCode(), p.GetPosition().x, p.GetPosition().y) for fp in board.GetFootprints() for p in fp.Pads()}
    n = 0
    traces = [t for t in board.GetTracks() if t.Type() == pcbnew.PCB_TRACE_T]
    for v in [t for t in board.GetTracks() if t.Type() == pcbnew.PCB_VIA_T]:
        if v.GetNetname() == "GND":
            continue
        k = (v.GetNetCode(), v.GetPosition().x, v.GetPosition().y)
        if len(ends.get(k, ())) < 2:    # a track may also pass through it without ending there
            ends.setdefault(k, set()).update(t.GetLayer() for t in traces
                                             if t.GetNetCode() == k[0] and t.HitTest(v.GetPosition()))
        if len(ends.get(k, ())) < 2 and k not in pads and ("via", k[1], k[2]) not in keep:
            board.Remove(v)
            n += 1
    return n


def _drop_stubs(board, limit=0.6):
    """Short tracks the router left with one end on nothing."""
    import pcbnew
    n = 0
    for _ in range(3):
        ends = {}
        for t in board.GetTracks():
            pts = [t.GetPosition()] if t.Type() == pcbnew.PCB_VIA_T else [t.GetStart(), t.GetEnd()]
            for p in pts:
                ends[(t.GetNetCode(), p.x, p.y)] = ends.get((t.GetNetCode(), p.x, p.y), 0) + 1
        pads = [p for fp in board.GetFootprints() for p in fp.Pads()]
        drop = []
        others = list(board.GetTracks())
        for t in board.GetTracks():
            if t.Type() != pcbnew.PCB_TRACE_T or t.GetLength() > pcbnew.FromMM(limit):
                continue
            for p in (t.GetStart(), t.GetEnd()):
                if ends[(t.GetNetCode(), p.x, p.y)] > 1:
                    continue
                if any(q.GetNetCode() == t.GetNetCode() and q.IsOnLayer(t.GetLayer()) and q.HitTest(p) for q in pads):
                    continue
                # an end in the middle of another track or on a via is a junction, not a stub
                if any(o is not t and o.GetNetCode() == t.GetNetCode() and o.HitTest(p)
                       and (o.Type() == pcbnew.PCB_VIA_T or (o.GetLayer() == t.GetLayer() and o not in drop))
                       for o in others):
                    continue
                drop.append(t)
                break
        if not drop:
            break
        for t in drop:
            board.Remove(t)
        n += len(drop)
    return n


def _join_islands(board, allow):
    """Each piece of a ground pour that has pads but no via or through-hole of its own gets a via
    into the plane, wherever one fits. Returns the pieces left without."""
    import pcbnew
    import pcbgen
    net = board.FindNet("GND")
    left = 0
    items = [t for t in board.GetTracks()] + [p for fp in board.GetFootprints() for p in fp.Pads()]
    holes = [t.GetPosition() for t in board.GetTracks() if t.Type() == pcbnew.PCB_VIA_T and t.GetNetCode() == net.GetNetCode()]
    holes += [p.GetPosition() for fp in board.GetFootprints() for p in fp.Pads()
              if p.GetNetCode() == net.GetNetCode() and p.GetAttribute() == pcbnew.PAD_ATTRIB_PTH]
    step = pcbnew.FromMM(0.1)
    for z in board.Zones():
        if z.GetIsRuleArea() or z.GetNetCode() != net.GetNetCode() or z.GetLayer() == pcbnew.In1_Cu:
            continue
        polys = z.GetFilledPolysList(z.GetLayer())
        for i in range(polys.OutlineCount()):
            one = pcbnew.SHAPE_POLY_SET()
            one.AddOutline(polys.Outline(i))
            for h in range(polys.HoleCount(i)):
                one.AddHole(polys.Hole(i, h))
            if any(one.Contains(h) for h in holes):
                continue
            bb = one.BBox()
            done = False
            y = bb.GetTop()
            while y <= bb.GetBottom() and not done:
                x = bb.GetLeft()
                while x <= bb.GetRight() and not done:
                    p = pcbnew.VECTOR2I(x, y)
                    x += step
                    if not one.Contains(p, -1, 0) or not allow(pcbnew.ToMM(p.x), pcbnew.ToMM(p.y)):
                        continue
                    via = pcbnew.PCB_VIA(board)
                    via.SetPosition(p)
                    via.SetWidth(pcbnew.FromMM(0.45))
                    via.SetDrill(pcbnew.FromMM(0.2))
                    via.SetNet(net)
                    trk = pcbnew.PCB_TRACK(board)
                    trk.SetStart(p)
                    trk.SetEnd(p)
                    trk.SetWidth(pcbnew.FromMM(0.45))
                    trk.SetLayer(z.GetLayer())
                    trk.SetNet(net)
                    smd = any(q.GetAttribute() == pcbnew.PAD_ATTRIB_SMD and q.GetEffectiveShape(
                        pcbnew.F_Cu if q.IsOnLayer(pcbnew.F_Cu) else pcbnew.B_Cu).Collide(
                            pcbnew.SHAPE_CIRCLE(p, pcbnew.FromMM(0.225)), pcbnew.FromMM(0.05))
                        for q in items if q.Type() == pcbnew.PCB_PAD_T and q.GetBoundingBox().Contains(p))
                    if not smd and pcbgen._clear(board, via, trk, items, net, pcbnew.FromMM(0.135)):
                        board.Add(via)
                        items.append(via)
                        holes.append(p)
                        done = True
                y += step
            if not done:
                left += 1
                c = bb.GetCenter()
                print(f"  no via fits in the {board.GetLayerName(z.GetLayer())} pour piece at "
                      f"({pcbnew.ToMM(c.x) - 100:.1f}, {pcbnew.ToMM(c.y) - 100:.1f}), "
                      f"{pcbnew.ToMM(bb.GetWidth()):.1f} x {pcbnew.ToMM(bb.GetHeight()):.1f} mm")
    return left


