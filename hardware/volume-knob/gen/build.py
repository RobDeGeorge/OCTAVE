import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
PROJ = os.path.dirname(HERE)
NAME = "volume-knob"
SCH = os.path.join(PROJ, NAME + ".kicad_sch")
PCB = os.path.join(PROJ, NAME + ".kicad_pcb")
REV = "0"
DATE = "2026-11-22"
TITLE = "OCTAVE wireless volume knob"

RAILS = ("GND", "VBUS", "VBAT", "3V3", "VLED")
SIGNAL_WIDTH, SIGNAL_CLEARANCE = 0.15, 0.15    # what the routers work to
DRC_CLEARANCE = 0.127                          # what the board is checked against (JLCPCB's floor is 0.09)


def run(cmd, **kw):
    print("+", " ".join(cmd))
    return subprocess.run(cmd, check=False, **kw)


def project_files():
    with open(os.path.join(PROJ, "sym-lib-table"), "w") as f:
        f.write('(sym_lib_table\n\t(version 7)\n\t(lib (name "OCTAVE") (type "KiCad") '
                '(uri "${KIPRJMOD}/lib/OCTAVE.kicad_sym") (options "") (descr "OCTAVE project symbols"))\n)\n')
    with open(os.path.join(PROJ, "fp-lib-table"), "w") as f:
        f.write('(fp_lib_table\n\t(version 7)\n\t(lib (name "OCTAVE") (type "KiCad") '
                '(uri "${KIPRJMOD}/lib/OCTAVE.pretty") (options "") (descr "OCTAVE project footprints"))\n)\n')
    # JLCPCB 4-layer capabilities, with a little margin
    rules = {"min_clearance": 0.127, "min_track_width": 0.127, "min_via_diameter": 0.45,
             "min_via_annular_width": 0.1, "min_through_hole_diameter": 0.2, "min_hole_to_hole": 0.25,
             "min_copper_edge_clearance": 0.3, "min_silk_clearance": 0.0, "min_text_height": 0.8,
             "min_text_thickness": 0.12, "min_hole_clearance": 0.2}
    pro = {"meta": {"filename": NAME + ".kicad_pro", "version": 3},
           "board": {"design_settings": {"rules": rules}}, "schematic": {}, "libraries": {},
           "net_settings": {"meta": {"version": 4}, "classes": [{
               "name": "Default", "priority": 2147483647, "clearance": DRC_CLEARANCE,
               "track_width": SIGNAL_WIDTH, "via_diameter": 0.5, "via_drill": 0.25,
               "microvia_diameter": 0.3, "microvia_drill": 0.1, "diff_pair_width": 0.2, "diff_pair_gap": 0.25,
               "diff_pair_via_gap": 0.25, "bus_width": 12, "wire_width": 6, "line_style": 0,
               "pcb_color": "rgba(0, 0, 0, 0.000)", "schematic_color": "rgba(0, 0, 0, 0.000)"}]}}
    with open(os.path.join(PROJ, NAME + ".kicad_pro"), "w") as f:
        json.dump(pro, f, indent=2)


def sch():
    import libdefs
    from mklib import write
    write(libdefs.SYMBOLS)
    project_files()
    import knob
    d = knob.d
    nets, problems = d.check()
    if problems:
        sys.exit("design problems:\n" + "\n".join(problems))
    from schgen import PAPER, SchWriter
    PAPER.update({"A3": (420, 297), "A2": (594, 420)})
    for paper in ("A3", "A2", "A1"):
        w = SchWriter(d, paper)
        w.power_flags(["GND", "VBUS"])
        w.layout(sheet_w=PAPER[paper][0] - 20, y_top=45)
        problems = w.check()
        if not any("sheet content reaches" in s for s in problems):
            break
    if problems:
        sys.exit("schematic layout problems:\n" + "\n".join(problems))
    w.write(SCH, TITLE, REV, DATE, comments=(
        "Generated by gen/build.py: edit the Python, not this sheet.",
        "Nets are joined by label: same name = same net."))
    rpt = os.path.join(PROJ, "erc.rpt")
    run(["kicad-cli", "sch", "erc", "--severity-all", SCH, "-o", rpt], capture_output=True)
    print(open(rpt).read().split("** ERC messages")[1].split("\n")[0] if os.path.exists(rpt) else "no report")
    print(len(d.parts), "parts,", len(nets), "nets, paper", paper)


def pcb():
    import pcbnew
    import knob
    import layout
    import pcbgen
    d = knob.d
    board = pcbgen.new_board(4)
    ds = board.GetDesignSettings()
    ds.SetCopperLayerCount(4)
    ds.m_TrackMinWidth = pcbnew.FromMM(0.127)
    ds.m_ViasMinSize = pcbnew.FromMM(0.45)
    ds.m_MinThroughDrill = pcbnew.FromMM(0.2)
    ds.m_MinClearance = pcbnew.FromMM(0.127)
    ds.m_CopperEdgeClearance = pcbnew.FromMM(0.3)
    fps, nets = pcbgen.add_footprints(board, d, sch_name=NAME)
    for fp in fps.values():
        r = fp.Reference()
        r.SetTextSize(pcbnew.VECTOR2I(pcbnew.FromMM(0.8), pcbnew.FromMM(0.8)))
        r.SetTextThickness(pcbnew.FromMM(0.12))
        r.SetVisible(False)     # no room on the disc: the assembly drawing names the parts
    for pad in fps["U2"].Pads():     # the charger's thermal pad and its vias: solid into the pours
        if pad.GetNetname() == "GND":
            pad.SetLocalZoneConnection(pcbnew.ZONE_CONNECTION_FULL)
    for pad in fps["U4"].Pads():     # 0.2 mm lands at 0.4 mm pitch: a 0.03 mm mask margin leaves a 0.14 mm web
        pad.SetLocalSolderMaskMargin(pcbnew.FromMM(0.03))
    for pad in fps["BT1"].Pads():    # soldered by hand: spokes into the planes, not solid copper
        pad.SetLocalZoneConnection(pcbnew.ZONE_CONNECTION_THERMAL)
    failed = layout.place_all(board, d, fps)
    if failed:
        print("NOT PLACED (no free spot near the target):", " ".join(failed))
    # silkscreen: nothing over the edge (the module, the socket and the cell all reach it), no dot
    # under the boost converter; a + on both sides at the cell's positive hole
    import math
    silk = (pcbnew.F_SilkS, pcbnew.B_SilkS)
    for ref, fp in fps.items():
        for g in list(fp.GraphicalItems()):
            if g.GetLayer() not in silk:
                continue
            bb = g.GetBoundingBox()
            far = max(math.hypot(pcbnew.ToMM(x) - layout.CX, pcbnew.ToMM(y) - layout.CY)
                      for x in (bb.GetLeft(), bb.GetRight()) for y in (bb.GetTop(), bb.GetBottom()))
            if far > layout.R_BOARD - 0.5 or ref in ("U4", "U7", "L1"):
                fp.Remove(g)
    plus = [p for p in fps["BT1"].Pads() if p.GetNumber() == "1"][0].GetPosition()
    for layer, text in ((pcbnew.F_SilkS, "+"), (pcbnew.B_SilkS, "+")):
        t = pcbnew.PCB_TEXT(board)
        t.SetText(text)
        t.SetLayer(layer)
        t.SetPosition(pcbnew.VECTOR2I(plus.x - pcbnew.FromMM(0.2), plus.y - pcbnew.FromMM(2.0)))
        t.SetTextSize(pcbnew.VECTOR2I(pcbnew.FromMM(1.4), pcbnew.FromMM(1.4)))
        t.SetTextThickness(pcbnew.FromMM(0.25))
        t.SetMirrored(layer == pcbnew.B_SilkS)
        board.Add(t)
    import art
    art.apply(board)            # the wizard, the quote and the name, on the top outside the LED ring
    fps.update(pcbgen.add_holes(board, [(layout.CX + x, layout.CY + y) for x, y in layout.HOLES],
                                layout.HOLE_KEEP, footprint="MountingHole:MountingHole_2.2mm_M2"))
    # fiducials for the pick-and-place camera, and names at the test pads
    for i, (x, y, back) in enumerate(layout.FIDUCIALS, 1):
        fp = pcbnew.FootprintLoad(*pcbgen.footprint_path("Fiducial:Fiducial_1mm_Mask2mm"))
        fp.SetReference(f"FID{i}")
        fp.Reference().SetVisible(False)
        fp.SetAttributes(pcbnew.FP_BOARD_ONLY | pcbnew.FP_EXCLUDE_FROM_BOM | pcbnew.FP_EXCLUDE_FROM_POS_FILES)
        board.Add(fp)
        layout.put(fp, x, y, 0, back)
        fps[fp.GetReference()] = fp
    taken = {}
    for fp in fps.values():
        for pad in fp.Pads():
            bb = pad.GetBoundingBox()
            for back in ([True, False] if pad.GetAttribute() == pcbnew.PAD_ATTRIB_PTH else [fp.IsFlipped()]):
                taken.setdefault(back, []).append((bb.GetLeft(), bb.GetTop(), bb.GetRight(), bb.GetBottom()))
    for ref, fp in sorted(fps.items()):
        if not ref.startswith("TP"):
            continue
        pos, back = fp.GetPosition(), fp.IsFlipped()
        if ref in knob.IO_ROW:      # the expansion holes: named on the top, along the radius, inside the row
            a = math.atan2(pcbnew.ToMM(pos.y) - layout.CY, pcbnew.ToMM(pos.x) - layout.CX)
            t = pcbnew.PCB_TEXT(board)
            t.SetText({"UART_TX": "IO21", "BOOT": "IO9"}.get(fp.GetValue(), fp.GetValue()))
            t.SetLayer(pcbnew.F_SilkS)
            t.SetPosition(pcbnew.VECTOR2I(pcbnew.FromMM(layout.CX + (layout.IO_R - 2.7) * math.cos(a)),
                                          pcbnew.FromMM(layout.CY + (layout.IO_R - 2.7) * math.sin(a))))
            t.SetTextSize(pcbnew.VECTOR2I(pcbnew.FromMM(0.8), pcbnew.FromMM(0.8)))
            t.SetTextThickness(pcbnew.FromMM(0.12))
            t.SetTextAngle(pcbnew.EDA_ANGLE(180 - math.degrees(a), pcbnew.DEGREES_T))
            board.Add(t)
            continue
        name = {"UART_TX": "TX", "BOOST_EN": "BEN", "LED_D1": "LED"}.get(fp.GetValue(), fp.GetValue())
        hw, hh = pcbnew.FromMM(0.4 * len(name) + 0.15), pcbnew.FromMM(0.55)
        for dx, dy in ((0, -1.2), (0, 1.2), (-0.7 - 0.4 * len(name), 0), (0.7 + 0.4 * len(name), 0)):
            cx, cy = pos.x + pcbnew.FromMM(dx), pos.y + pcbnew.FromMM(dy)
            box = (cx - hw, cy - hh, cx + hw, cy + hh)
            far = max(math.hypot(pcbnew.ToMM(x) - layout.CX, pcbnew.ToMM(y) - layout.CY)
                      for x in (box[0], box[2]) for y in (box[1], box[3]))
            if far > layout.R_BOARD - 0.6 or any(
                    box[0] < o[2] and o[0] < box[2] and box[1] < o[3] and o[1] < box[3] for o in taken.get(back, ())):
                continue
            t = pcbnew.PCB_TEXT(board)
            t.SetText(name)
            t.SetLayer(pcbnew.B_SilkS if back else pcbnew.F_SilkS)
            t.SetPosition(pcbnew.VECTOR2I(cx, cy))
            t.SetTextSize(pcbnew.VECTOR2I(pcbnew.FromMM(0.8), pcbnew.FromMM(0.8)))
            t.SetTextThickness(pcbnew.FromMM(0.12))
            t.SetMirrored(back)
            board.Add(t)
            taken.setdefault(back, []).append(box)
            break
    # no copper on any layer beside or under the antenna, rim to rim
    every = (pcbnew.F_Cu, pcbnew.In1_Cu, pcbnew.In2_Cu, pcbnew.B_Cu)
    # (the piece of the disc above the keep-out line; not a rectangle reaching past the edge, which
    # sent the autorouter off the board)
    a0 = math.asin(-layout.ANTENNA_Y / layout.R_BOARD)
    arc = [(layout.CX + layout.R_BOARD * math.cos(a), layout.CY - layout.R_BOARD * math.sin(a))
           for a in (a0 + (math.pi - 2 * a0) * k / 40 for k in range(41))]
    pcbgen.keepout_poly(board, arc, "antenna: no copper", every)
    for i, (x, y, back) in enumerate(layout.FIDUCIALS, 1):   # the camera wants bare board round each dot
        pcbgen.keepout_circle(board, layout.CX + x, layout.CY + y, 1.15, f"FID{i}",
                              layers=(pcbnew.B_Cu if back else pcbnew.F_Cu,))
    # the boost converter's lands stay copper-defined: no pour and no vias under it
    u4 = fps["U4"].GetPosition()
    ux, uy = pcbnew.ToMM(u4.x), pcbnew.ToMM(u4.y)
    pcbgen.keepout_rect(board, ux - 0.75, uy - 0.95, ux + 0.75, uy + 0.95, "boost: no pour", (pcbnew.B_Cu,),
                        tracks=False)
    # the encoder's boss and locating pin go through the board: no copper within 0.45 mm of either hole
    pcbgen.keepout_circle(board, layout.CX, layout.CY, 1.5, "encoder boss")
    pcbgen.keepout_circle(board, layout.CX, layout.CY + 4.5, 1.45, "encoder locating pin")
    # the outline: the disc, with a notch under and beside the module's antenna (Espressif: the antenna
    # past the board's edge, or the board cut away under it and on both sides). The pours stop 0.3 mm short
    nx, ny = layout.ANTENNA_NOTCH_X, layout.ANTENNA_Y - 0.15
    pcbgen.notched_outline(board, layout.CX, layout.CY, layout.R_BOARD, nx, ny)
    # In1 is the ground plane (Freerouting sees it as a power layer); F, In2 and B carry the signals
    # and are poured with GND after routing
    pcbgen.circle_zone(board, nets["GND"], pcbnew.In1_Cu, layout.CX, layout.CY, layout.R_BOARD, solid=True)
    board.Save(PCB)
    print("placed", len(fps) - len(layout.HOLES), "footprints,", len(layout.HOLES), "mounting holes")


