#!/usr/bin/env python3
"""Regenerate the OBD adapter's KiCad project from obd_adapter.py.

    python3 build.py sch      # symbol lib + schematic + ERC
    python3 build.py pcb      # board (placement from layout.py), DSN for Freerouting
    python3 build.py route    # Freerouting -> import -> zones -> DRC
    python3 build.py fab      # gerbers, drill, BOM + CPL for JLCPCB
    python3 build.py all

Uses the system python3 (pcbnew lives there), not the repo venv.
"""

import json
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
PROJ = os.path.dirname(HERE)
NAME = "obd-adapter"
SCH = os.path.join(PROJ, NAME + ".kicad_sch")
PCB = os.path.join(PROJ, NAME + ".kicad_pcb")
REV = "0"
DATE = "2026-11-02"
TITLE = "OCTAVE OBD adapter (bring-up board)"


def run(cmd, **kw):
    print("+", " ".join(cmd))
    return subprocess.run(cmd, check=False, **kw)


def project_files():
    with open(os.path.join(PROJ, "sym-lib-table"), "w") as f:
        f.write('(sym_lib_table\n\t(version 7)\n\t(lib (name "OCTAVE") (type "KiCad") '
                '(uri "${KIPRJMOD}/lib/OCTAVE.kicad_sym") (options "") (descr "OCTAVE project symbols"))\n)\n')
    # JLCPCB 4-layer capabilities, with a little margin
    rules = {"min_clearance": 0.15, "min_track_width": 0.15, "min_via_diameter": 0.45,
             "min_via_annular_width": 0.1, "min_through_hole_diameter": 0.2, "min_hole_to_hole": 0.25,
             "min_copper_edge_clearance": 0.3, "min_silk_clearance": 0.0, "min_text_height": 0.8,
             "min_text_thickness": 0.12, "min_hole_clearance": 0.2}
    pro = {"meta": {"filename": NAME + ".kicad_pro", "version": 3},
           "board": {"design_settings": {"rules": rules}}, "schematic": {}, "libraries": {}}
    with open(os.path.join(PROJ, NAME + ".kicad_pro"), "w") as f:
        json.dump(pro, f, indent=2)


def sch():
    import libdefs
    from mklib import write
    write(libdefs.SYMBOLS)
    project_files()
    import obd_adapter
    from schgen import SchWriter
    d = obd_adapter.d
    nets, problems = d.check()
    if problems:
        sys.exit("design problems:\n" + "\n".join(problems))
    w = SchWriter(d, paper="A1")
    w.layout(sheet_w=800)
    w.power_flags({"GND", "VBAT_IN", "VBUS", "VBAT_F", "VBAT_P", "5V", "VDDA", "DLC_SW", "CMP_VCC"})
    w.write(SCH, TITLE, REV, DATE, comments=(
        "Generated by hardware/obd-adapter/gen/build.py from obd_adapter.py: edit the Python, not this sheet.",
        "Every pin is joined by net label; same name = same net."))
    rpt = os.path.join(PROJ, "erc.rpt")
    run(["kicad-cli", "sch", "erc", "--severity-all", SCH, "-o", rpt], capture_output=True)
    print(open(rpt).read().split("** ERC messages")[1].split("\n")[0] if os.path.exists(rpt) else "no report")


def pcb():
    import pcbnew
    import layout
    import obd_adapter
    import pcbgen
    d = obd_adapter.d
    board = pcbgen.new_board(4)
    ds = board.GetDesignSettings()
    ds.SetCopperLayerCount(4)
    ds.m_TrackMinWidth = pcbnew.FromMM(0.15)
    ds.m_ViasMinSize = pcbnew.FromMM(0.45)
    ds.m_MinThroughDrill = pcbnew.FromMM(0.2)  # JLCPCB 4-layer minimum; the PowerPAD thermal vias are 0.2
    ds.m_MinClearance = pcbnew.FromMM(0.15)
    ds.m_CopperEdgeClearance = pcbnew.FromMM(0.3)
    fps, nets = pcbgen.add_footprints(board, d, sch_name=NAME)
    for fp in fps.values():
        r = fp.Reference()
        r.SetTextSize(pcbnew.VECTOR2I(pcbnew.FromMM(0.8), pcbnew.FromMM(0.8)))
        r.SetTextThickness(pcbnew.FromMM(0.12))
    layout.place_all(board, d, fps)
    pcbgen.outline(board, 0, 0, layout.W, layout.H)
    gnd = nets["/GND"]
    pcbgen.zone(board, gnd, pcbnew.In1_Cu, 0, 0, layout.W, layout.H, clearance=0.25)
    board.Save(PCB)
    print("placed", len(fps), "footprints")


# track widths in um; anything not listed is 200. Keep a class no wider than the smallest pad it
# lands on (Freerouting does not neck down): 3V3 and VDDA reach 0.3 mm LQFP pins, VBUS the USB-C.
WIDTHS = {
    600: ["VBAT_IN", "VBAT_F", "VBAT_P", "BUCK_SW", "5V_BUCK", "5V"],
    400: ["VBUS", "3V3_ESP", "DLC_SW", "VJ1850", "KLINE", "LLINE"],
    250: ["3V3", "VDDA", "GND"],
}


def _dsn_postprocess(text):
    """In1.Cu becomes the GND plane; supply nets get their own width classes."""
    import re
    text = text.replace("(layer In1.Cu\n      (type signal)", "(layer In1.Cu\n      (type power)")
    m = re.search(r"\(class kicad_default (.*?)\(circuit", text, re.S)
    names = m.group(1).split()
    special = {"/" + n for nets in WIDTHS.values() for n in nets}
    keep = [n for n in names if n not in special]
    via = '(circuit\n        (use_via "Via[0-3]_600:300_um")\n      )'

    def cls(name, nets, width, clear=200):
        return (f"(class {name} {' '.join('/' + n for n in nets)}\n      {via}\n"
                f"      (rule\n        (width {width})\n        (clearance {clear})\n      )\n    )\n    ")
    new = "(class kicad_default " + " ".join(keep) + "\n      (circuit"
    classes = "".join(cls(f"w{w}", nets, w) for w, nets in WIDTHS.items())
    text = text[:m.start()] + classes + new + text[m.end():]
    return text


def _snapshot(board, before):
    """Plain data for every track / via added since `before` (a set of KIIDs)."""
    import pcbnew
    out = []
    for t in board.GetTracks():
        if t.m_Uuid.AsString() in before:
            continue
        if t.Type() == pcbnew.PCB_VIA_T:
            out.append(("via", t.GetPosition(), t.GetWidth(pcbnew.F_Cu), t.GetDrillValue(), t.GetNetname()))
        else:
            out.append(("trk", t.GetStart(), t.GetEnd(), t.GetWidth(), t.GetLayer(), t.GetNetname()))
    return out


def _restore(board, items):
    import pcbnew
    for it in items:
        if it[0] == "via":
            _, pos, w, drill, net = it
            v = pcbnew.PCB_VIA(board)
            v.SetPosition(pos)
            v.SetWidth(w)
            v.SetDrill(drill)
            v.SetNet(board.FindNet(net))
            v.SetLocked(True)
            board.Add(v)
        else:
            _, a, b, w, layer, net = it
            t = pcbnew.PCB_TRACK(board)
            t.SetStart(a)
            t.SetEnd(b)
            t.SetWidth(w)
            t.SetLayer(layer)
            t.SetNet(board.FindNet(net))
            t.SetLocked(True)
            board.Add(t)


def route():
    """GND first (fan-out + MCU star, locked), then Freerouting for the rest, then stitching + pours."""
    import pcbnew
    import layout
    import obd_adapter
    import pcbgen
    work = os.path.join(PROJ, "route")
    os.makedirs(work, exist_ok=True)
    dsn, ses = os.path.join(work, NAME + ".dsn"), os.path.join(work, NAME + ".ses")
    keepout = [(76, 0, 110, 7.0)]  # ESP32 antenna

    board = pcbnew.LoadBoard(PCB)
    before = {t.m_Uuid.AsString() for t in board.GetTracks()}
    mcu = [p for p in obd_adapter.d.parts if p.value == "STM32G474RET6"][0].ref
    mx, my, _ = layout.fixed_for(obd_adapter.d)[mcu]
    bad = pcbgen.star(board, "/GND", [(mcu, n) for n in ("15", "27", "31", "47", "63")], mx, my)
    print("MCU ground star, not joined:", bad or "none")
    bad = pcbgen.fanout(board, "/GND", pcbnew.In1_Cu, keepouts=keepout)
    print("GND fan-out, pads without a via:", bad or "none")
    for t in board.GetTracks():
        t.SetLocked(True)
    gnd_items = _snapshot(board, before)
    board.Save(PCB)

    pcbnew.ExportSpecctraDSN(board, dsn)
    with open(dsn) as f:
        text = _dsn_postprocess(f.read())
    with open(dsn, "w") as f:
        f.write(text)
    if os.path.exists(ses):
        os.remove(ses)
    run(["timeout", "2400", "/opt/freerouting/bin/freerouting", "-de", dsn, "-do", ses,
         "--gui.enabled=false", "-mp", "200"], stdout=open(os.path.join(work, "freerouting.log"), "w"),
        stderr=subprocess.STDOUT)
    if not os.path.exists(ses):
        sys.exit("freerouting produced no session; see route/freerouting.log")

    board = pcbnew.LoadBoard(PCB)
    pcbnew.ImportSpecctraSES(board, ses)
    # the import replaces every track with the session's; put the GND fan-out back if it went
    have = {(pcbnew.ToMM(t.GetPosition().x), pcbnew.ToMM(t.GetPosition().y)) for t in board.GetTracks()
            if t.Type() == pcbnew.PCB_VIA_T}
    missing = [it for it in gnd_items if not (it[0] == "via" and
                                              (pcbnew.ToMM(it[1].x), pcbnew.ToMM(it[1].y)) in have)]
    if any(it[0] == "via" for it in missing):
        _restore(board, missing)
    print("stitching vias:", pcbgen.stitch(board, "/GND", 2, 2, 108, 73, pitch=3.0, keepouts=keepout))
    gnd = board.FindNet("/GND")
    for layer in (pcbnew.F_Cu, pcbnew.B_Cu):
        pcbgen.zone(board, gnd, layer, 0, 0, layout.W, layout.H, clearance=0.3, solid=True)
    # 3V3 pour on In2 around the routed signals: a low-impedance feed to the ESP32, MCU and flash
    pcbgen.zone(board, board.FindNet("/3V3"), pcbnew.In2_Cu, 0, 0, layout.W, layout.H, clearance=0.3)
    pcbnew.ZONE_FILLER(board).Fill(board.Zones())
    board.Save(PCB)
    drc()


def drc():
    rpt = os.path.join(PROJ, "drc.rpt")
    run(["kicad-cli", "pcb", "drc", "--schematic-parity", "--severity-all", PCB, "-o", rpt],
        capture_output=True)
    for line in open(rpt):
        if line.startswith("** Found"):
            print(line.strip())


def _natural(ref):
    head = ref.rstrip("0123456789")
    return head, int(ref[len(head):] or 0)


def fab():
    """Gerbers + drill (zipped), JLCPCB BOM and CPL, a hand-fit list."""
    import csv
    import shutil
    import obd_adapter
    out = os.path.join(PROJ, "fab")
    gdir = os.path.join(out, "gerbers")
    shutil.rmtree(out, ignore_errors=True)
    os.makedirs(gdir)
    layers = "F.Cu,In1.Cu,In2.Cu,B.Cu,F.Paste,B.Paste,F.Silkscreen,B.Silkscreen,F.Mask,B.Mask,Edge.Cuts"
    run(["kicad-cli", "pcb", "export", "gerbers", "--layers", layers, "--subtract-soldermask",
         "-o", gdir + "/", PCB], capture_output=True)
    run(["kicad-cli", "pcb", "export", "drill", "--format", "excellon", "--excellon-separate-th",
         "--generate-map", "--map-format", "gerberx2", "-o", gdir + "/", PCB], capture_output=True)
    shutil.make_archive(os.path.join(out, f"{NAME}-rev{REV}-gerbers"), "zip", gdir)
    # BOM: group by value + footprint + LCSC
    groups, hand = {}, []
    for p in obd_adapter.d.parts:
        if p.dnp:
            continue
        if not p.lcsc:
            if not p.lib_id.startswith(("Connector:TestPoint", "Jumper:SolderJumper")):  # bare pads
                hand.append(p)
            continue
        key = (p.value, p.footprint.split(":")[1], p.lcsc)
        groups.setdefault(key, []).append(p.ref)
    with open(os.path.join(out, f"{NAME}-rev{REV}-bom-jlcpcb.csv"), "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["Comment", "Designator", "Footprint", "LCSC"])
        for (val, fp, lcsc), refs in sorted(groups.items(), key=lambda kv: kv[1][0]):
            w.writerow([val, ",".join(sorted(refs, key=_natural)), fp, lcsc])
    with open(os.path.join(out, f"{NAME}-rev{REV}-hand-fit.txt"), "w") as f:
        f.write("Not assembled by JLCPCB (no LCSC number): fit by hand or leave off.\n\n")
        for p in hand:
            f.write(f"{p.ref:6} {p.value:22} {p.footprint}\n")
    # CPL from KiCad's position file
    pos = os.path.join(out, "pos.csv")
    run(["kicad-cli", "pcb", "export", "pos", "--format", "csv", "--units", "mm", "--side", "both",
         "--exclude-dnp", "-o", pos, PCB], capture_output=True)
    assembled = {r for refs in groups.values() for r in refs}
    with open(pos) as fin, open(os.path.join(out, f"{NAME}-rev{REV}-cpl-jlcpcb.csv"), "w", newline="") as fout:
        w = csv.writer(fout)
        w.writerow(["Designator", "Mid X", "Mid Y", "Layer", "Rotation"])
        for row in csv.DictReader(fin):
            if row["Ref"] in assembled:
                w.writerow([row["Ref"], row["PosX"] + "mm", row["PosY"] + "mm",
                            "Top" if row["Side"] == "top" else "Bottom", row["Rot"]])
    os.remove(pos)
    print("fab outputs in", out, ":", sorted(os.listdir(out)))
    print(len(assembled), "parts assembled,", len(groups), "BOM lines,", len(hand), "hand-fit")


