#!/usr/bin/env python3
"""Regenerate the OBD adapter's KiCad project from obd_adapter.py.

    python3 build.py sch      # symbol lib + schematic + ERC
    python3 build.py pcb      # board (placement from layout.py), DSN for Freerouting
    python3 build.py route    # Freerouting -> import -> zones -> DRC
    python3 build.py fab      # gerbers, drill, BOM + CPL for JLCPCB
    python3 build.py all

Uses the system python3 (pcbnew lives there), not the repo venv.
"""

import json
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
PROJ = os.path.dirname(HERE)
NAME = "obd-adapter"
SCH = os.path.join(PROJ, NAME + ".kicad_sch")
PCB = os.path.join(PROJ, NAME + ".kicad_pcb")
REV = "0"
DATE = "2026-11-02"
TITLE = "OCTAVE OBD adapter (bring-up board)"


def run(cmd, **kw):
    print("+", " ".join(cmd))
    return subprocess.run(cmd, check=False, **kw)


def project_files():
    with open(os.path.join(PROJ, "sym-lib-table"), "w") as f:
        f.write('(sym_lib_table\n\t(version 7)\n\t(lib (name "OCTAVE") (type "KiCad") '
                '(uri "${KIPRJMOD}/lib/OCTAVE.kicad_sym") (options "") (descr "OCTAVE project symbols"))\n)\n')
    # JLCPCB 4-layer capabilities, with a little margin
    rules = {"min_clearance": 0.15, "min_track_width": 0.15, "min_via_diameter": 0.45,
             "min_via_annular_width": 0.1, "min_through_hole_diameter": 0.2, "min_hole_to_hole": 0.25,
             "min_copper_edge_clearance": 0.3, "min_silk_clearance": 0.0, "min_text_height": 0.8,
             "min_text_thickness": 0.12, "min_hole_clearance": 0.2}
    pro = {"meta": {"filename": NAME + ".kicad_pro", "version": 3},
           "board": {"design_settings": {"rules": rules}}, "schematic": {}, "libraries": {},
           # signals may go to 0.15 / 0.15 mm (JLCPCB's floor is 0.09), for room round the LQFP-64;
           # the frozen Rev 0 routing is 0.2 / 0.2 almost everywhere (the DSN rule only picked this up
           # after it was routed). Supply nets have their own widths (WIDTHS); battery-side nets keep
           # HV_CLEARANCE (.kicad_dru)
           "net_settings": {"meta": {"version": 4}, "classes": [{
               "name": "Default", "priority": 2147483647, "clearance": SIGNAL_CLEARANCE / 1000,
               "track_width": SIGNAL_WIDTH / 1000, "via_diameter": 0.6, "via_drill": 0.3,
               "microvia_diameter": 0.3, "microvia_drill": 0.1, "diff_pair_width": 0.2, "diff_pair_gap": 0.25,
               "diff_pair_via_gap": 0.25, "bus_width": 12, "wire_width": 6, "line_style": 0,
               "pcb_color": "rgba(0, 0, 0, 0.000)", "schematic_color": "rgba(0, 0, 0, 0.000)"}]}}
    with open(os.path.join(PROJ, NAME + ".kicad_pro"), "w") as f:
        json.dump(pro, f, indent=2)
    # battery-side nets keep HV_CLEARANCE from everything else (Freerouting gets the same rule
    # through the DSN classes; this makes KiCad's DRC and interactive router enforce it too)
    cond = " || ".join(f"A.NetName == '/{n}'" for n in sorted(HV))
    with open(os.path.join(PROJ, NAME + ".kicad_dru"), "w") as f:
        f.write("(version 1)\n"
                f"(rule \"battery-side clearance\"\n  (condition \"({cond}) && A.NetName != B.NetName\")\n"
                f"  (constraint clearance (min {HV_CLEARANCE / 1000:.2f}mm)))\n")


def sch():
    import libdefs
    from mklib import write
    write(libdefs.SYMBOLS)
    project_files()
    import obd_adapter
    from schgen import SchWriter
    d = obd_adapter.d
    nets, problems = d.check()
    if problems:
        sys.exit("design problems:\n" + "\n".join(problems))
    w = SchWriter(d, paper="A0")
    w.layout(sheet_w=1150)
    w.power_flags({"GND", "VBAT_IN", "VBUS", "VBUS2", "VBAT_F", "VBAT_P", "5V", "VDDA", "DLC_SW", "CMP_VCC", "5V_BUCK"})
    problems = w.check()
    if problems:
        sys.exit("schematic layout problems:\n" + "\n".join(problems))
    w.write(SCH, TITLE, REV, DATE, comments=(
        "Generated by gen/build.py: edit the Python, not this sheet.",
        "Every pin is joined by net label; same name = same net."))
    rpt = os.path.join(PROJ, "erc.rpt")
    run(["kicad-cli", "sch", "erc", "--severity-all", SCH, "-o", rpt], capture_output=True)
    print(open(rpt).read().split("** ERC messages")[1].split("\n")[0] if os.path.exists(rpt) else "no report")


def pcb():
    import pcbnew
    import layout
    import obd_adapter
    import pcbgen
    d = obd_adapter.d
    board = pcbgen.new_board(4)
    ds = board.GetDesignSettings()
    ds.SetCopperLayerCount(4)
    ds.m_TrackMinWidth = pcbnew.FromMM(0.15)
    ds.m_ViasMinSize = pcbnew.FromMM(0.45)
    ds.m_MinThroughDrill = pcbnew.FromMM(0.2)  # JLCPCB 4-layer minimum; the PowerPAD thermal vias are 0.2
    ds.m_MinClearance = pcbnew.FromMM(0.15)
    ds.m_CopperEdgeClearance = pcbnew.FromMM(0.3)
    fps, nets = pcbgen.add_footprints(board, d, sch_name=NAME)
    for fp in fps.values():
        r = fp.Reference()
        r.SetTextSize(pcbnew.VECTOR2I(pcbnew.FromMM(0.8), pcbnew.FromMM(0.8)))
        r.SetTextThickness(pcbnew.FromMM(0.12))
    layout.place_all(board, d, fps)
    for ref, (x, y, angle) in layout.LABELS.items():
        r = fps[ref].Reference()
        r.SetPosition(pcbnew.VECTOR2I(pcbnew.FromMM(x), pcbnew.FromMM(y)))
        r.SetTextAngleDegrees(angle)
    pcbgen.outline(board, 0, 0, layout.W, layout.H)
    # In1 is the GND plane (Freerouting sees it as a power layer); In2 is poured with 3V3 after routing
    pcbgen.zone(board, nets["/GND"], pcbnew.In1_Cu, 0, 0, layout.W, layout.H, clearance=0.25, solid=True)
    for fp in fps.values():
        for pad in fp.Pads():
            if pad.GetAttribute() == pcbnew.PAD_ATTRIB_PTH and fp.GetValue().startswith("ESP32"):
                ls = pad.GetLayerSet()  # module ground-pad vias: tent the bottom (no solder wicking out)
                ls.RemoveLayer(pcbnew.B_Mask)
                pad.SetLayerSet(ls)
    board.Save(PCB)
    print("placed", len(fps), "footprints")


# track widths in um; anything not listed is 200. Keep a class no wider than the smallest pad it
# lands on (Freerouting does not neck down): 3V3 and VDDA reach 0.3 mm LQFP pins, VBUS the USB-C.
WIDTHS = {
    1200: ["VBAT_IN"],
    600: ["VBAT_F", "VBAT_P", "BUCK_SW", "5V"],
    # 5V_BUCK's power path (L1 -> output caps -> OR diode) is pre-routed at 1.0-1.2 mm; what is
    # left to route are branches to the CAN VCC pins (~70 mA each), the VPW reference and the FB divider
    400: ["5V_BUCK", "VBUS", "VBUS2", "3V3_ESP", "DLC_SW", "VJ1850", "KLINE", "LLINE", "KLINE_PU", "LLINE_PU"],
    250: ["3V3", "VDDA", "GND"],
}
# nets that can sit at battery voltage (or ring like the switch node): wider clearance to the rest
HV = {"VBAT_IN", "VBAT_F", "VBAT_P", "DLC_SW", "DLC_SW_G", "KLINE", "LLINE", "KLINE_PU", "LLINE_PU",
      "J1850_P", "J1850_N", "J1850_PD", "VJ1850", "CMP_VCC", "K_IN", "BUCK_SW",
      "CAN1_H", "CAN1_L", "CAN2_H", "CAN2_L",
      # also at bus / battery potential: the TERM node (120R to CAN_H, the jumper to CAN_L), the ideal
      # diode's gate drive (above VBAT) and the buck's bootstrap (rides the switch node)
      "CAN1_TERM", "CAN2_TERM", "IDEAL_GATE", "IDEAL_VCAP", "BUCK_BOOT"}
HV_CLEARANCE = 300
SIGNAL_WIDTH, SIGNAL_CLEARANCE = 150, 150   # um, the Default net class
# nets the maze router lays before Freerouting runs (OBD_SEED=/A,/B sets them)
SEED = []   # tried: seeding the ten nets earlier runs failed made Freerouting leave 12 instead of 4
if "OBD_SEED" in os.environ:
    SEED = [n for n in os.environ["OBD_SEED"].split(",") if n]


def _width_of(net):
    for w, nets in WIDTHS.items():
        if net.lstrip("/") in nets:
            return max(w, SIGNAL_WIDTH) / 1000
    return SIGNAL_WIDTH / 1000


def _clearance_of(net):
    return (HV_CLEARANCE if net.lstrip("/") in HV else SIGNAL_CLEARANCE) / 1000


def _dsn_postprocess(text):
    """In1.Cu becomes the GND plane; supply nets get their own width classes."""
    import re
    text = text.replace("(layer In1.Cu\n      (type signal)", "(layer In1.Cu\n      (type power)")
    # the default rule comes from the board's Default net class, which LoadBoard doesn't read
    # from the .kicad_pro: set the signal width / clearance here
    text = re.sub(r"\(rule\s+\(width 200\)\s+\(clearance 200\)",
                  f"(rule\n      (width {SIGNAL_WIDTH})\n      (clearance {SIGNAL_CLEARANCE})", text, count=1)
    if IN2_PLANE:   # In2 is the 3V3 plane: signals on F.Cu / B.Cu only
        text = text.replace("(layer In2.Cu\n      (type signal)", "(layer In2.Cu\n      (type power)")
    # every 3V3 pad has its own via into In2, which is poured after routing: give Freerouting one
    # 3V3 pin only, so it doesn't spend board space joining them with tracks
    text = re.sub(r"\(net /3V3\s+\(pins (\S+)[^)]*\)", r"(net /3V3\n      (pins \1)", text)
    # In2 stays a signal layer (poured with 3V3 after routing; every 3V3 pad has its own via into it).
    # Freerouting 2.2 ignores every net when the DSN carries autoroute_settings, so no layer costs here.
    rules = ""
    import prewire
    ko = ""
    for i, (x0, y0, x1, y1) in enumerate(prewire.KEEPOUTS):
        ko += f"(keepout \"k{i}\" (rect F.Cu {x0 * 1000:.0f} {-y1 * 1000:.0f} {x1 * 1000:.0f} {-y0 * 1000:.0f}))\n    "
    # In2 around the LDO tab: no signals, so the 3V3 pour there is solid and its vias reach the plane
    x0, y0, x1, y1 = prewire.LDO_TAB
    ko += "" if IN2_PLANE else f"(keepout \"ldo_in2\" (rect In2.Cu {(x0 - 1) * 1000:.0f} {-(y1 + 1.5) * 1000:.0f} {(x1 + 2.5) * 1000:.0f} {-(y0 - 1.5) * 1000:.0f}))\n    "
    i = text.index("\n    (via \"Via[")  # the structure's via list (it names every via size on the board)
    text = text[:i + 5] + ko + rules + text[i + 5:]
    m = re.search(r"\(class kicad_default (.*?)\(circuit", text, re.S)
    names = m.group(1).split()
    special = {"/" + n for nets in WIDTHS.values() for n in nets}
    keep = [n for n in names if n not in special]
    via = '(circuit\n        (use_via "Via[0-3]_600:300_um")\n      )'

    outer = '(circuit\n        (use_via "Via[0-3]_600:300_um")\n        (use_layer F.Cu B.Cu)\n      )'

    def cls(name, nets, width, clear=200):
        # power-current nets stay off the 0.5 oz inner layer (a fault before the PTC trips could fuse
        # it); battery-side signals (K/L, J1850, DLC_SW: <= 0.2 A, current-limited) may use In2
        v = outer if (width >= 600 or "VBUS" in nets) else via
        return (f"(class {name} {' '.join('/' + n for n in nets)}\n      {v}\n"
                f"      (rule\n        (width {width})\n        (clearance {clear})\n      )\n    )\n    ")
    hv_plain = [n for n in HV if "/" + n not in special and "/" + n in names]
    keep = [n for n in keep if n[1:] not in HV]
    new = "(class kicad_default " + " ".join(keep) + "\n      (circuit"
    classes = ""
    for w, nets in WIDTHS.items():
        lo = [n for n in nets if n not in HV]
        hi = [n for n in nets if n in HV]
        if lo:
            classes += cls(f"w{w}", lo, w)
        if hi:
            classes += cls(f"w{w}hv", hi, w, HV_CLEARANCE)
    if hv_plain:
        classes += cls("hv", hv_plain, 200, HV_CLEARANCE)
    text = text[:m.start()] + classes + new + text[m.end():]
    return text


def _snapshot(board, before):
    """Plain data for every track / via added since `before` (a set of KIIDs)."""
    import pcbnew
    out = []
    for t in board.GetTracks():
        if t.m_Uuid.AsString() in before:
            continue
        if t.Type() == pcbnew.PCB_VIA_T:
            out.append(("via", t.GetPosition(), t.GetWidth(pcbnew.F_Cu), t.GetDrillValue(), t.GetNetname()))
        else:
            out.append(("trk", t.GetStart(), t.GetEnd(), t.GetWidth(), t.GetLayer(), t.GetNetname()))
    return out


def _restore(board, items):
    import pcbnew
    for it in items:
        if it[0] == "via":
            _, pos, w, drill, net = it
            v = pcbnew.PCB_VIA(board)
            v.SetPosition(pos)
            v.SetWidth(w)
            v.SetDrill(drill)
            v.SetNet(board.FindNet(net))
            v.SetLocked(True)
            board.Add(v)
        else:
            _, a, b, w, layer, net = it
            t = pcbnew.PCB_TRACK(board)
            t.SetStart(a)
            t.SetEnd(b)
            t.SetWidth(w)
            t.SetLayer(layer)
            t.SetNet(board.FindNet(net))
            t.SetLocked(True)
            board.Add(t)


# In2: the 3V3 plane (signals on F.Cu / B.Cu), or a signal layer poured with 3V3 after routing
IN2_PLANE = True
FREEROUTING_JAR = os.environ.get("FREEROUTING_JAR", os.path.expanduser(
    "~/.local/share/freerouting/freerouting-2.5.0.jar"))


def route():
    """Hand copper first (power stage, locked), then GND / 3V3 fan-out to the planes, then
    Freerouting for the rest on F / B, then stitching, local copper and pours."""
    import pcbnew
    import layout
    import obd_adapter
    import pcbgen
    import prewire
    work = os.path.join(PROJ, "route")
    os.makedirs(work, exist_ok=True)
    dsn, ses = os.path.join(work, NAME + ".dsn"), os.path.join(work, NAME + ".ses")
    keepout = list(layout.KEEPOUTS)  # ESP32 antenna
    d = obd_adapter.d

    board = pcbnew.LoadBoard(PCB)
    if os.path.exists(FROZEN) and not os.environ.get("OBD_REROUTE"):
        print(f"routing: replaying {_replay(board)} frozen tracks / vias from gen/routing.json")
        _copper(board, d, keepout, stitch=False)    # stitching vias are part of the frozen routing
        pcbnew.ZONE_FILLER(board).Fill(board.Zones())
        board.Save(PCB)
        drc()
        return
    before = {t.m_Uuid.AsString() for t in board.GetTracks()}
    prewire.wire(board, d)
    mcu = [p for p in d.parts if p.value == "STM32G474RET6"][0].ref
    mx, my, _ = layout.fixed_for(d)[mcu]
    bad = pcbgen.star(board, "/GND", [(mcu, n) for n in ("15", "27", "31", "47", "63")], mx, my)
    print("MCU ground star, not joined:", bad or "none")
    bad = pcbgen.fanout(board, "/GND", pcbnew.In1_Cu, keepouts=keepout,
                       hv=HV, hv_clearance=HV_CLEARANCE / 1000)
    print("GND fan-out, pads without a via:", bad or "none")
    bad = pcbgen.fanout(board, "/3V3", pcbnew.In2_Cu, keepouts=keepout,
                       hv=HV, hv_clearance=HV_CLEARANCE / 1000)
    print("3V3 fan-out, pads without a via:", bad or "none")
    if SEED:    # nets Freerouting keeps leaving boxed in: route them first, on a near-empty board
        import maze
        left = maze.finish(board, _width_of, _clearance_of, prewire.KEEPOUTS + keepout, skip=("/GND", "/3V3"),
                           hv=HV, hv_clearance=HV_CLEARANCE / 1000, only=set(SEED))
        print("seeded before Freerouting:", [n for n in SEED if n not in left], "failed:", left or "none")
    for t in board.GetTracks():
        t.SetLocked(True)
    pre_items = _snapshot(board, before)
    if IN2_PLANE:   # exported to the DSN as the 3V3 plane; every 3V3 pad's fan-out via lands on it
        pcbgen.zone(board, board.FindNet("/3V3"), pcbnew.In2_Cu, 0, 0, layout.W, layout.H, clearance=0.3, solid=True)
    board.Save(PCB)

    def freeroute(board, log, edit=None):
        pcbnew.ExportSpecctraDSN(board, dsn)
        with open(dsn) as f:
            text = _dsn_postprocess(f.read())
        if edit:
            text = edit(text)
        with open(dsn, "w") as f:
            f.write(text)
        if os.path.exists(ses):
            os.remove(ses)
        # Freerouting >= 2.5 (2.2.4 loops forever in PolylineTrace.normalize on this board's
        # pre-routed copper). FREEROUTING_JAR overrides; a finished run takes ~4 min here.
        for attempt in range(3):
            subprocess.run(["timeout", "1200", "java", "-jar", FREEROUTING_JAR, "-de", dsn, "-do", ses,
                            "--gui.enabled=false", "--feature_flags.multi_threading=false", "-mp", "200",
                            "--router.automatic_neckdown=false", "--router.copper_to_edge_clearance_um=400",
                            "--usage_and_diagnostic_data.disable_analytics=true"],
                           stdout=open(os.path.join(work, log), "w"), stderr=subprocess.STDOUT)
            if os.path.exists(ses):
                break
            print(f"freerouting gave no session (attempt {attempt + 1}), retrying")
        if not os.path.exists(ses):
            sys.exit(f"freerouting produced no session; see route/{log}")
        pcbnew.ImportSpecctraSES(board, ses)
        for t in board.GetTracks():   # Freerouting necks down at some pads despite the setting
            if t.Type() == pcbnew.PCB_TRACE_T and t.GetWidth() < pcbnew.FromMM(0.15):
                t.SetWidth(pcbnew.FromMM(0.15))

    def unrouted(board):
        if IN2_PLANE:
            pcbnew.ZONE_FILLER(board).Fill(board.Zones())
            board.BuildConnectivity()
            return board.GetConnectivity().GetUnconnectedCount(False)
        # 3V3 pads all have a via to In2 and are joined by the In2 pour after routing: count with it
        z = pcbgen.zone(board, board.FindNet("/3V3"), pcbnew.In2_Cu, 0, 0, layout.W, layout.H,
                        clearance=0.3, solid=True)
        pcbnew.ZONE_FILLER(board).Fill(board.Zones())
        board.BuildConnectivity()
        n = board.GetConnectivity().GetUnconnectedCount(False)
        board.Remove(z)
        board.BuildConnectivity()
        return n

    def key(t):
        if t.Type() == pcbnew.PCB_VIA_T:
            return ("via", t.GetPosition().x, t.GetPosition().y)
        return ("trk", t.GetStart().x, t.GetStart().y, t.GetEnd().x, t.GetEnd().y, t.GetLayer())

    fixed = {("via", it[1].x, it[1].y) if it[0] == "via" else ("trk", it[1].x, it[1].y, it[2].x, it[2].y, it[4])
             for it in pre_items}
    board = pcbnew.LoadBoard(PCB)
    freeroute(board, "freerouting.log")
    # Freerouting stalls with a few connections left on a dense board: lock what it routed and
    # run it again on the remainder (a fresh start on a smaller problem usually finishes them)
    for i in range(3):
        left = unrouted(board)
        print(f"unrouted after pass {i + 1}: {left}")
        if not left:
            break
        # only the pre-routed copper stays fixed: Freerouting may rip up its own tracks to finish
        for t in board.GetTracks():
            t.SetLocked(key(t) in fixed)
        freeroute(board, f"freerouting-{i + 2}.log")
    # the import replaces every track with the session's; put back any pre-routed item it dropped
    have = {key(t) for t in board.GetTracks()}
    missing = []
    for it in pre_items:
        k = ("via", it[1].x, it[1].y) if it[0] == "via" else ("trk", it[1].x, it[1].y, it[2].x, it[2].y, it[4])
        if k not in have:
            missing.append(it)
    _restore(board, missing)
    print("pre-routed items restored after import:", len(missing))
    ldo = _copper(board, d, keepout, stitch=True)
    pcbnew.ZONE_FILLER(board).Fill(board.Zones())
    if not IN2_PLANE:
        left = _bridge_3v3(board, ldo, prewire.KEEPOUTS + layout.KEEPOUTS)
        if left:
            print("3V3 pads still cut off from the pour:", [p.GetParentFootprint().GetReference() + "." + p.GetNumber() for p in left])
    # Freerouting stalls with a few connections left: finish them with the grid router
    import maze
    left = maze.finish(board, _width_of, _clearance_of, prewire.KEEPOUTS, skip=("/GND", "/3V3"), hv=HV, hv_clearance=HV_CLEARANCE / 1000)
    print("nets still in pieces after the finisher:", left or "none")
    board.Save(PCB)
    drc()


def _copper(board, d, keepout, stitch):
    """Local copper and pours after routing: LDO tab area, GND stitching, F/B GND pours, In2,
    pad connection overrides. Returns the LDO's reference."""
    import pcbnew
    import layout
    import pcbgen
    import prewire
    # LDO tab: a 3V3 copper area on F.Cu with vias into the In2 plane (heat + low impedance)
    ldo = [p for p in d.parts if p.value == "AP2114H-3.3"][0].ref
    q = board.FindFootprintByReference(ldo).GetPosition()
    lx, ly = pcbnew.ToMM(q.x), pcbnew.ToMM(q.y)
    tab = prewire.LDO_TAB
    assert tab[0] - 1 < lx + 3.15 < tab[2], "LDO moved: update layout.LDO_TAB"
    pcbgen.zone(board, board.FindNet("/3V3"), pcbnew.F_Cu, *tab, clearance=0.3, priority=2, solid=True)
    if stitch:
        print("stitching vias:", pcbgen.stitch(board, "/GND", 2, 2, 108, 73, pitch=3.0, keepouts=keepout,
                                                clearance=HV_CLEARANCE / 1000))
    gnd = board.FindNet("/GND")
    for layer in (pcbnew.F_Cu, pcbnew.B_Cu):
        pcbgen.zone(board, gnd, layer, 0, 0, layout.W, layout.H, clearance=0.3, solid=False)
    if not any(z.GetNetname() == "/3V3" and z.IsOnLayer(pcbnew.In2_Cu) for z in board.Zones()):
        pcbgen.zone(board, board.FindNet("/3V3"), pcbnew.In2_Cu, 0, 0, layout.W, layout.H, clearance=0.3, solid=True)
    # thermal relief on the pours (no tombstoned 0603s); big pads and the exposed pads stay solid
    for fp in board.GetFootprints():
        for pad in fp.Pads():
            if pad.GetNetname() not in ("/GND", "/3V3"):
                continue
            sz = pad.GetSize(pcbnew.F_Cu) if hasattr(pad, "GetSize") else pad.GetSize()
            area = pcbnew.ToMM(sz.x) * pcbnew.ToMM(sz.y)
            # through-hole GND pins too: the pour round a connector pin is often crowded down to one
            # spoke or an island (KiCad's starved_thermal); the pin reaches In1 through its barrel anyway
            if area >= 3.0 or pad.GetAttribute() == pcbnew.PAD_ATTRIB_PTH:
                pad.SetLocalZoneConnection(pcbnew.ZONE_CONNECTION_FULL)
    return ldo


# The finished routing, frozen: `build.py freeze` writes every track and via of the current board
# here (Freerouting's, the finisher's and any routed by hand in KiCad). While it exists, `route`
# replays it instead of routing, so a rebuild gives the same board. OBD_REROUTE=1 routes afresh.
FROZEN = os.path.join(HERE, "routing.json")


def _placement(board):
    import pcbnew
    return {fp.GetReference(): [round(pcbnew.ToMM(fp.GetPosition().x), 4), round(pcbnew.ToMM(fp.GetPosition().y), 4),
                                round(fp.GetOrientationDegrees(), 2)] for fp in board.GetFootprints()}


def freeze():
    """Save the current board's routing (every track and via) to gen/routing.json."""
    import pcbnew
    board = pcbnew.LoadBoard(PCB)
    items = []
    for t in board.GetTracks():
        if t.Type() == pcbnew.PCB_VIA_T:
            items.append({"via": [t.GetPosition().x, t.GetPosition().y], "d": t.GetWidth(pcbnew.F_Cu),
                          "drill": t.GetDrillValue(), "net": t.GetNetname()})
        elif t.Type() == pcbnew.PCB_TRACE_T:
            items.append({"trk": [t.GetStart().x, t.GetStart().y, t.GetEnd().x, t.GetEnd().y], "w": t.GetWidth(),
                          "layer": board.GetLayerName(t.GetLayer()), "net": t.GetNetname()})
        else:
            sys.exit(f"freeze: unsupported track type {t.GetClass()} (arcs?)")
    with open(FROZEN, "w") as f:
        json.dump({"placement": _placement(board), "items": items}, f, indent=0)
    print(f"froze {len(items)} tracks / vias into {FROZEN}")


def _replay(board):
    import pcbnew
    with open(FROZEN) as f:
        data = json.load(f)
    now = _placement(board)
    moved = sorted(r for r in set(now) | set(data["placement"]) if now.get(r) != data["placement"].get(r))
    if moved:
        sys.exit(f"placement changed since the routing was frozen ({', '.join(moved[:12])}"
                 f"{' ...' if len(moved) > 12 else ''}): route afresh with OBD_REROUTE=1, or move them back")
    for it in data["items"]:
        n = board.FindNet(it["net"])
        if "via" in it:
            v = pcbnew.PCB_VIA(board)
            v.SetPosition(pcbnew.VECTOR2I(*it["via"]))
            v.SetWidth(it["d"])
            v.SetDrill(it["drill"])
            v.SetNet(n)
            v.SetLocked(True)
            board.Add(v)
        else:
            t = pcbnew.PCB_TRACK(board)
            t.SetStart(pcbnew.VECTOR2I(*it["trk"][:2]))
            t.SetEnd(pcbnew.VECTOR2I(*it["trk"][2:]))
            t.SetWidth(it["w"])
            t.SetLayer(board.GetLayerID(it["layer"]))
            t.SetNet(n)
            t.SetLocked(True)
            board.Add(t)
    return len(data["items"])


def _cluster(board, net, seed):
    """KIIDs of every pad, track and via of `net` copper-connected to `seed`, zone fills included."""
    import pcbnew
    board.BuildConnectivity()
    con = board.GetConnectivity()
    items = [t for t in board.GetTracks() if t.GetNetname() == net]
    items += [p for fp in board.GetFootprints() for p in fp.Pads() if p.GetNetname() == net]
    parent = {i.m_Uuid.AsString(): i.m_Uuid.AsString() for i in items}

    def find(u):
        while parent[u] != u:
            parent[u] = parent[parent[u]]
            u = parent[u]
        return u

    def join(a, b):
        if a in parent and b in parent:
            parent[find(a)] = find(b)
    for it in items:
        for n in con.GetConnectedItems(it):
            join(it.m_Uuid.AsString(), n.m_Uuid.AsString())
    for z in board.Zones():
        if z.GetNetname() != net:
            continue
        for layer in z.GetLayerSet().Seq():
            fill = z.GetFilledPolysList(layer)
            for k in range(fill.OutlineCount()):
                anchor = f"zone{z.m_Uuid.AsString()}:{layer}:{k}"
                parent[anchor] = anchor
                for it in items:
                    if not it.IsOnLayer(layer):
                        continue
                    pos = it.GetPosition() if it.Type() != pcbnew.PCB_TRACE_T else it.GetStart()
                    if fill.Contains(pos, k) or (it.Type() == pcbnew.PCB_TRACE_T and fill.Contains(it.GetEnd(), k)):
                        join(it.m_Uuid.AsString(), anchor)
    root = find(seed.m_Uuid.AsString())
    return {i.m_Uuid.AsString() for i in items if find(i.m_Uuid.AsString()) == root}


def _bridge_3v3(board, ldo, keepouts):
    """Join 3V3 copper cut off from the main In2 pour (In2 signal tracks can wall a pocket in).

    KiCad exports the pour to the DSN as its outline, so Freerouting can't see these pockets.
    For each one, add a jumper: a via in the pocket, a via in the main pour and the shortest
    B.Cu (else F.Cu) track between them that clears every other net on every layer.
    Returns the pads still cut off.
    """
    import pcbnew
    import prewire
    net, MM, ToMM = "/3V3", pcbnew.FromMM, pcbnew.ToMM
    L4 = (pcbnew.F_Cu, pcbnew.In1_Cu, pcbnew.In2_Cu, pcbnew.B_Cu)
    tab = max((p for p in board.FindFootprintByReference(ldo).Pads() if p.GetNumber() == "2"),
              key=lambda p: p.GetSize(pcbnew.F_Cu).y)
    in2 = [z for z in board.Zones() if z.GetNetname() == net and z.IsOnLayer(pcbnew.In2_Cu)][0]
    hv = set(HV)
    iso = []
    for _ in range(6):
        pcbnew.ZONE_FILLER(board).Fill(board.Zones())
        main = _cluster(board, net, tab)
        pads = [p for fp in board.GetFootprints() for p in fp.Pads() if p.GetNetname() == net]
        iso = [p for p in pads if p.m_Uuid.AsString() not in main]
        if not iso:
            return []
        island = _cluster(board, net, iso[0])
        fill = in2.GetFilledPolysList(pcbnew.In2_Cu)
        vias = lambda ids: [t.GetPosition() for t in board.GetTracks() if t.Type() == pcbnew.PCB_VIA_T  # noqa: E731
                            and t.m_Uuid.AsString() in ids]
        k_main = {k for k in range(fill.OutlineCount()) for q in vias(main) if fill.Contains(q, k)}
        k_isl = {k for k in range(fill.OutlineCount()) for q in vias(island) if fill.Contains(q, k)}
        if not k_isl:
            return iso
        # everything a new via / track must clear: other nets on all layers, own-net holes
        obs = []
        for o in list(board.GetTracks()) + [p for fp in board.GetFootprints() for p in fp.Pads()]:
            own = o.GetNetname() == net
            if own and not (o.Type() == pcbnew.PCB_VIA_T or getattr(o, "GetAttribute", lambda: None)() in
                            (pcbnew.PAD_ATTRIB_PTH, pcbnew.PAD_ATTRIB_NPTH)):
                continue
            bb = o.GetBoundingBox()
            gap = MM(0.25) if own else MM(0.35 if o.GetNetname().lstrip("/") in hv else 0.25)
            obs.append((bb.GetLeft(), bb.GetTop(), bb.GetRight(), bb.GetBottom(), o, gap))

        def clear(shape, layers, box):
            x0, y0, x1, y1 = box
            for l, t, r, bt, o, gap in obs:
                if r < x0 - MM(1) or l > x1 + MM(1) or bt < y0 - MM(1) or t > y1 + MM(1):
                    continue
                if any(o.IsOnLayer(L) and o.GetEffectiveShape(L).Collide(shape, gap) for L in layers):
                    return False
            return True

        def spots(ks, box):
            x0, y0, x1, y1 = box
            out = []
            for xi in range(int(x0), int(x1), MM(0.25)):
                for yi in range(int(y0), int(y1), MM(0.25)):
                    pt = pcbnew.VECTOR2I(xi, yi)
                    x, y = ToMM(xi), ToMM(yi)
                    if any(a - 0.5 < x < c + 0.5 and b - 0.5 < y < d + 0.5 for a, b, c, d in keepouts):
                        continue
                    if not any(fill.Contains(pt, k) for k in ks):
                        continue
                    if clear(pcbnew.SHAPE_CIRCLE(pt, MM(0.3)), L4, (xi, yi, xi, yi)):
                        out.append(pt)
            return out
        boxes = [fill.Outline(k).BBox() for k in k_isl]
        ib = (min(b.GetLeft() for b in boxes), min(b.GetTop() for b in boxes),
              max(b.GetRight() for b in boxes), max(b.GetBottom() for b in boxes))
        a_pts = spots(k_isl, ib)
        b_pts = spots(k_main, (ib[0] - MM(4), ib[1] - MM(4), ib[2] + MM(4), ib[3] + MM(4)))
        pairs = sorted(((a - b).EuclideanNorm(), i, j) for i, a in enumerate(a_pts) for j, b in enumerate(b_pts)
                       if (a - b).EuclideanNorm() < MM(4))
        done = False
        for _, i, j in pairs:
            a, b = a_pts[i], b_pts[j]
            seg = pcbnew.SHAPE_SEGMENT(a, b, MM(0.3))
            box = (min(a.x, b.x), min(a.y, b.y), max(a.x, b.x), max(a.y, b.y))
            for layer in (pcbnew.B_Cu, pcbnew.F_Cu):
                if clear(seg, (layer,), box):
                    pa, pb = (ToMM(a.x), ToMM(a.y)), (ToMM(b.x), ToMM(b.y))
                    prewire.via(board, net, *pa)
                    prewire.via(board, net, *pb)
                    prewire.track(board, net, [pa, pb], 0.3, layer)
                    print(f"3V3 pocket ({', '.join(p.GetParentFootprint().GetReference() + '.' + p.GetNumber() for p in iso)}):"
                          f" jumper {pa} -> {pb} on {board.GetLayerName(layer)}")
                    done = True
                    break
            if done:
                break
        if not done:
            return iso
    return iso


